# Evidence register
# ---------------------------------------------------------------------------
EVIDENCE: list[dict] = []


def EV(eid: str, study_id: str, doc_id: str, page: int, quote: str, supports: str) -> str:
    EVIDENCE.append(
        {
            "evidence_id": eid,
            "study_id": study_id,
            "doc_id": doc_id,
            "page": page,
            "quote": " ".join(quote.split()),
            "supports": supports,
        }
    )
    return eid


